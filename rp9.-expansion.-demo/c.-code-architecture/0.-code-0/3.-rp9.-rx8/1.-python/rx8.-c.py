def write_text(path, content):
    path.write_text(content, encoding="utf-8")


def write_json(path, data):
    path.write_text(
        json.dumps(data, indent=4, ensure_ascii=False),
        encoding="utf-8"
    )


def to_jsonable(value):
    if isinstance(value, Fraction):
        return str(value)
    if isinstance(value, Path):
        return str(value)
    if isinstance(value, dict):
        return {str(k): to_jsonable(v) for k, v in value.items()}
    if isinstance(value, list):
        return [to_jsonable(v) for v in value]
    if isinstance(value, tuple):
        return [to_jsonable(v) for v in value]
    return value


def status(pass_value):
    return "PASS" if pass_value else "FAIL"


def make_test_record(
    test_id,
    title,
    what_is_tested,
    how_it_is_tested,
    why_it_is_tested,
    expected_result,
    observed_result,
    passed,
    data,
):
    return {
        "test_id": test_id,
        "title": title,
        "what_is_tested": what_is_tested,
        "how_it_is_tested": how_it_is_tested,
        "why_it_is_tested": why_it_is_tested,
        "expected_result": expected_result,
        "observed_result": observed_result,
        "result": status(passed),
        "data": to_jsonable(data),
    }


def test_1_complementary_value_relation():
    left = Fraction(1, 4)
    right = Fraction(3, 4)
    whole = left + right

    passed = whole == 1 and right == 1 - left

    return make_test_record(
        "TEST_1",
        "COMPLEMENTARY_VALUE_RELATION",
        "The complementary value relation 1/4 and 3/4 within one preserved whole.",
        "Uses exact rational arithmetic and checks both closure and complement.",
        "To verify the relation as a value identity without assigning it to a geometric form.",
        "1/4 + 3/4 = 1 and 3/4 = 1 - 1/4.",
        f"Whole = {whole}; complement of 1/4 = {1-left}.",
        passed,
        {
            "left_position": left,
            "right_position": right,
            "whole": whole,
            "closure": left + right,
            "complement_of_left": 1 - left,
        },
    )


def test_2_binary_scale_extension():
    start = Fraction(1, 1)
    positions = [start / (2 ** n) for n in range(4)]
    expected = [
        Fraction(1, 1),
        Fraction(1, 2),
        Fraction(1, 4),
        Fraction(1, 8),
    ]

    passed = positions == expected

    return make_test_record(
        "TEST_2",
        "BINARY_SCALE_EXTENSION",
        "Repeated binary scaling of one established value.",
        "Applies the same division-by-two operation recursively with exact rational arithmetic.",
        "To verify that later scale positions are generated by the same operation rather than by a new rule.",
        "1 -> 1/2 -> 1/4 -> 1/8.",
        "Generated positions: " + " -> ".join(str(v) for v in positions) + ".",
        passed,
        {
            "operation": "x 1/2",
            "positions": positions,
            "expected_positions": expected,
        },
    )


def test_3_scale_invariant_complement():
    scales = [Fraction(1, 1), Fraction(2, 1), Fraction(8, 1), Fraction(1, 8)]
    records = []
    passed = True

    for scale in scales:
        left = scale * Fraction(1, 4)
        right = scale * Fraction(3, 4)
        total = left + right
        ratio = right / left

        local_pass = total == scale and ratio == 3
        passed = passed and local_pass

        records.append({
            "scale": scale,
            "left": left,
            "right": right,
            "total": total,
            "right_to_left_ratio": ratio,
            "pass": local_pass,
        })

    return make_test_record(
        "TEST_3",
        "SCALE_INVARIANT_COMPLEMENT",
        "The 1/4 and 3/4 complementary relation under multiple exact scales.",
        "Scales both positions by the same factor and checks closure and the 3:1 ratio.",
        "To verify that scale changes the magnitude of the positions without changing their internal relation.",
        "For every tested scale S: S/4 + 3S/4 = S and (3S/4)/(S/4) = 3.",
        f"Checked {len(records)} exact scales; all preserved closure and ratio.",
        passed,
        {
            "tested_scales": records,
            "invariant_ratio": Fraction(3, 1),
        },
    )


def test_4_seven_plus_one_position_relation():
    active = 7
    reference = 1
    total = active + reference
    active_ratio = Fraction(active, total)
    reference_ratio = Fraction(reference, total)

    passed = (
        total == 8
        and active_ratio == Fraction(7, 8)
        and reference_ratio == Fraction(1, 8)
        and active_ratio + reference_ratio == 1
    )

    return make_test_record(
        "TEST_4",
        "SEVEN_PLUS_ONE_POSITION_RELATION",
        "The positional value relation 7 + 1 within a total of 8.",
        "Computes the total and the exact relative positions 7/8 and 1/8.",
        "To verify the value relation independently of any geometric interpretation.",
        "7 + 1 = 8; 7/8 + 1/8 = 1.",
        f"Total = {total}; active = {active_ratio}; reference = {reference_ratio}.",
        passed,
        {
            "active_value": active,
            "reference_value": reference,
            "total": total,
            "active_ratio": active_ratio,
            "reference_ratio": reference_ratio,
            "closure": active_ratio + reference_ratio,
        },
    )


def test_5_representational_projection():
    exact_positions = [
        Fraction(1, 2),
        Fraction(1, 4),
        Fraction(3, 4),
        Fraction(1, 8),
        Fraction(7, 8),
    ]

    records = []
    passed = True

    for value in exact_positions:
        decimal_value = float(value)
        recovered = Fraction.from_float(decimal_value)
        residual = recovered - value

        records.append({
            "exact_value": value,
            "decimal_value": decimal_value,
            "recovered_fraction": recovered,
            "residual": residual,
        })

        if not isinstance(decimal_value, float):
            passed = False

    return make_test_record(
        "TEST_5",
        "REPRESENTATIONAL_PROJECTION",
        "Projection of selected exact rational positions into machine decimal representation.",
        "Converts exact rational values to float and records the exact recovered machine value and residual.",
        "To keep exact functional values separate from their machine representation.",
        "Every selected exact position is projected and its representation residual is explicitly recorded.",
        f"Projected {len(records)} exact positions and recorded all residuals.",
        passed and len(records) == len(exact_positions),
        {
            "projection_records": records,
            "exact_values_remain_source_values": True,
        },
    )


def test_6_internal_validation_lock(previous_tests):
    failed = [test["test_id"] for test in previous_tests if test["result"] != "PASS"]
